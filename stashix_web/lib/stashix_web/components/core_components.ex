    - badge: overlaid bottom-left badge text (issue number, issue count)
    - type: :book | :series — controls fallback icon
  """
  attr :href, :string, required: true
  attr :title, :string, required: true
  attr :cover_url, :string, default: nil
  attr :width, :integer, default: nil
  attr :subtitle, :string, default: nil
  attr :badge, :string, default: nil
  attr :progress, :float, default: nil
  attr :type, :atom, default: :book
  attr :class, :string, default: ""

  def media_card(assigns) do
    assigns =
      assigns
      |> assign(:img_src, if(assigns.cover_url && assigns.width,
        do: "#{assigns.cover_url}?w=#{assigns.width}",
        else: assigns.cover_url
      ))
      |> assign(:cover_id, "cover-#{:erlang.phash2(assigns.href)}")

    ~H"""
    <a href={@href} class={["group rounded-xl overflow-hidden bg-gray-900 shadow-[0_0_12px_rgba(0,0,0,0.5)] hover:shadow-[0_0_18px_rgba(109,40,217,0.35)] hover:-translate-y-0.5 transition-all duration-200", @class]}>
      <div class="aspect-[2/3] bg-gray-800 relative">
        <%= if @img_src do %>
          <img
            id={@cover_id}
            phx-hook="CoverImage"
            src={@img_src}
            alt={@title}
            class="w-full h-full object-cover"
            onerror="this.style.display='none';this.nextElementSibling.style.display='flex'"
          />
          <div class="w-full h-full hidden items-center justify-center text-gray-600">
            <.media_card_fallback type={@type} />
          </div>
        <% else %>
          <div class="w-full h-full flex items-center justify-center text-gray-600">
            <.media_card_fallback type={@type} />
          </div>
        <% end %>
        <%= if @badge do %>
          <span class="absolute bottom-2 left-2 text-xs bg-black/70 text-gray-300 px-2 py-0.5 rounded-full backdrop-blur-sm font-medium opacity-0 group-hover:opacity-100 transition-opacity duration-200">
            {@badge}
          </span>
        <% end %>
        <div class="absolute inset-x-0 bottom-0 h-12 bg-gradient-to-t from-gray-900/80 to-transparent"></div>
        <%= if @progress do %>
          <%= if @progress >= 1.0 do %>
            <div class="absolute top-2 left-2 z-10 w-5 h-5 bg-green-500 rounded-full flex items-center justify-center shadow-lg">
              <svg class="w-3 h-3 text-white" fill="none" stroke="currentColor" viewBox="0 0 24 24">
                <path stroke-linecap="round" stroke-linejoin="round" stroke-width="3" d="M5 13l4 4L19 7" />
              </svg>
            </div>
          <% end %>
          <div class="absolute bottom-0 inset-x-0 h-1 bg-gray-700/60 z-10">
            <div
              class={"h-full transition-all #{if @progress >= 1.0, do: "bg-green-500", else: "bg-violet-500"}"}
              style={"width: #{round(min(@progress, 1.0) * 100)}%"}
            ></div>
          </div>
        <% end %>
      </div>
      <div class="px-2.5 py-2 bg-gray-900">
        <p class="text-xs font-medium text-gray-200 group-hover:text-white transition-colors line-clamp-2">{@title}</p>
        <%= if @subtitle do %>
          <p class="text-xs text-gray-500 mt-0.5">{@subtitle}</p>
        <% end %>
      </div>
    </a>
    """
  end

  attr :type, :atom, default: :book

  defp media_card_fallback(%{type: :series} = assigns) do
    ~H"""
    <svg class="w-8 h-8" fill="none" stroke="currentColor" viewBox="0 0 24 24">
      <path stroke-linecap="round" stroke-linejoin="round" stroke-width="1.5" d="M19 11H5m14 0a2 2 0 012 2v6a2 2 0 01-2 2H5a2 2 0 01-2-2v-6a2 2 0 012-2m14 0V9a2 2 0 00-2-2M5 11V9a2 2 0 012-2m0 0V5a2 2 0 012-2h6a2 2 0 012 2v2M7 7h10" />
    </svg>
    """
  end

  defp media_card_fallback(assigns) do
    ~H"""
    <svg class="w-8 h-8" fill="none" stroke="currentColor" viewBox="0 0 24 24">
      <path stroke-linecap="round" stroke-linejoin="round" stroke-width="1.5" d="M12 6.253v13m0-13C10.832 5.477 9.246 5 7.5 5S4.168 5.477 3 6.253v13C4.168 18.477 5.754 18 7.5 18s3.332.477 4.5 1.253m0-13C13.168 5.477 14.754 5 16.5 5c1.747 0 3.332.477 4.5 1.253v13C19.832 18.477 18.247 18 16.5 18c-1.746 0-3.332.477-4.5 1.253" />
    </svg>
    """
  end

  attr :page, :integer, required: true
  attr :total_pages, :integer, required: true
  attr :on_page, :string, default: "goto_page"

  def pagination(assigns) do
    assigns = assign(assigns, :pages, pagination_pages(assigns.page, assigns.total_pages))

    ~H"""
    <%= if @total_pages > 1 do %>
      <div class="flex items-center justify-center gap-1">
        <button
          phx-click={@on_page}
          phx-value-page={1}
          disabled={@page == 1}
          class="w-9 h-9 flex items-center justify-center text-sm rounded-lg border bg-gray-900 border-gray-700 text-gray-400 hover:bg-gray-800 hover:text-white disabled:opacity-30 disabled:cursor-not-allowed transition-colors"
        >
          <.icon name="lucide-chevron-first" class="w-4 h-4" />
        </button>
        <button
          phx-click={@on_page}
          phx-value-page={@page - 1}
          disabled={@page == 1}
          class="w-9 h-9 flex items-center justify-center text-sm rounded-lg border bg-gray-900 border-gray-700 text-gray-400 hover:bg-gray-800 hover:text-white disabled:opacity-30 disabled:cursor-not-allowed transition-colors"
        >
          <.icon name="lucide-chevron-left" class="w-4 h-4" />
        </button>

        <%= for {p, i} <- Enum.with_index(@pages, 1) do %>
          <button
            phx-click={@on_page}
            phx-value-page={p}
            class={[
              "w-9 h-9 flex items-center justify-center text-sm rounded-lg border transition-colors",
              if(i > 5, do: "hidden sm:flex", else: "flex"),
              if(p == @page,
                do: "bg-gray-100 border-gray-200 text-gray-900 font-semibold",
                else: "bg-gray-900 border-gray-700 text-gray-400 hover:bg-gray-800 hover:text-white"
              )
            ]}
          >
            {p}
          </button>
        <% end %>

        <button
          phx-click={@on_page}
          phx-value-page={@page + 1}
          disabled={@page == @total_pages}
          class="w-9 h-9 flex items-center justify-center text-sm rounded-lg border bg-gray-900 border-gray-700 text-gray-400 hover:bg-gray-800 hover:text-white disabled:opacity-30 disabled:cursor-not-allowed transition-colors"
        >
          <.icon name="lucide-chevron-right" class="w-4 h-4" />
        </button>
        <button
          phx-click={@on_page}
          phx-value-page={@total_pages}
          disabled={@page == @total_pages}
          class="w-9 h-9 flex items-center justify-center text-sm rounded-lg border bg-gray-900 border-gray-700 text-gray-400 hover:bg-gray-800 hover:text-white disabled:opacity-30 disabled:cursor-not-allowed transition-colors"
        >
          <.icon name="lucide-chevron-last" class="w-4 h-4" />
        </button>
      </div>
    <% end %>
    """
  end

  defp pagination_pages(_current, total) when total <= 11, do: Enum.to_list(1..total)

  defp pagination_pages(current, total) do
    half = 5
    start = max(1, min(current - half, total - 10))
    finish = min(total, start + 10)
    Enum.to_list(start..finish)
  end
end
